import { test, expect } from '../fixtures';
import { callsAction } from '../pages/base.page';
import { RequestErrorPage } from '../pages/request-error.page';

test('announcement table and dialog support keyboard dismissal, saved drafts, posting, and deletion', async ({ auth, announcements, page, db }) => {
    await auth.login('admin');
    await announcements.goto('/admin/announcements');
    const table = page.getByRole('table');
    await expect(table).toBeVisible();
    await expect(table.getByRole('columnheader')).toHaveText(['Announcement', 'Audience', 'Delivery', 'Posted', 'Actions']);
    await expect(table).toContainText('No announcements yet.');
    await expect(announcements.form).not.toBeVisible();
    await announcements.openCreate();
    const dialog = page.getByRole('dialog', { name: 'New announcement' });
    await expect(dialog.getByRole('button', { name: 'Close announcement dialog' })).toBeFocused();
    await page.keyboard.press('Shift+Tab');
    await expect(announcements.submit).toBeFocused();
    await page.keyboard.press('Tab');
    await expect(dialog.getByRole('button', { name: 'Close announcement dialog' })).toBeFocused();
    await announcements.fill('Floor maintenance notice', 'Keep the hallway clear during maintenance.');
    await page.getByLabel('Also email tenants').check();
    const audience = page.getByLabel('Audience');
    const floor = await audience.locator('option').nth(1).getAttribute('value');
    await audience.selectOption(floor!);
    await announcements.action('closeCreateModal', () => page.keyboard.press('Escape'));
    await expect(dialog).not.toBeVisible();
    await expect(page.getByRole('button', { name: 'New announcement', exact: true })).toBeFocused();
    expect(db.snapshot().announcements).toHaveLength(0);
    await announcements.openCreate();
    await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Floor maintenance notice');
    await expect(audience).toHaveValue(floor!);
    await expect(page.getByLabel('Also email tenants')).toBeChecked();
    await announcements.action('closeCreateModal', () => dialog.getByRole('button', { name: 'Cancel', exact: true }).click());
    await announcements.openCreate();
    await announcements.action('post', () => announcements.submit.click());
    await expect(dialog).not.toBeVisible();
    await expect(page).toHaveURL(/\/admin\/announcements$/);
    const row = table.getByRole('row').filter({ hasText: 'Floor maintenance notice' });
    await expect(row).toContainText('Keep the hallway clear during maintenance.');
    await expect(row).toContainText('Email');
    expect(db.snapshot().announcements).toEqual([expect.objectContaining({ title: 'Floor maintenance notice', emailed: 1, stall_location_id: Number(floor) })]);
    await test.info().attach('announcements-table', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
    await announcements.openCreate();
    await expect(page.getByLabel('Title', { exact: true })).toHaveValue('');
    await expect(page.getByLabel('Message', { exact: true })).toHaveValue('');
    await expect(audience).toHaveValue('');
    await expect(page.getByLabel('Also email tenants')).not.toBeChecked();
    await announcements.action('closeCreateModal', () => dialog.getByRole('button', { name: 'Close announcement dialog' }).click());
    page.once('dialog', prompt => prompt.accept());
    await announcements.action('delete', () => row.getByRole('button', { name: /Delete announcement/ }).click());
    await expect(table).toContainText('No announcements yet.');
    expect(db.snapshot().announcements).toHaveLength(0);
});

test('mobile announcement dialog preserves its draft after a failed post and recovers once', async ({ auth, announcements, page, db }) => {
    await page.setViewportSize({ width: 375, height: 812 });
    await auth.login('admin');
    await announcements.open();
    await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'));
    await announcements.fill('Mobile draft', 'A notice written on a narrow screen.');
    await page.route('**/livewire/update', route => callsAction(route.request(), 'post')
        ? route.fulfill({ status: 500, contentType: 'application/json', json: { message: 'QA raw response' } })
        : route.continue());
    await announcements.action('post', () => announcements.submit.click(), 500);
    await new RequestErrorPage(page).visible(/server could not complete/i, announcements.form);
    await expect(announcements.submit).toBeEnabled();
    await expect(page.getByLabel('Title', { exact: true })).toHaveValue('Mobile draft');
    await expect(page).toHaveURL(/\/admin\/announcements$/);
    expect(db.snapshot().announcements).toHaveLength(0);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    const box = await page.getByRole('dialog', { name: 'New announcement' }).locator('.modal-box').boundingBox();
    expect(box!.x).toBeGreaterThanOrEqual(0);
    expect(box!.x + box!.width).toBeLessThanOrEqual(375);
    await test.info().attach('announcements-mobile-error', { body: await page.screenshot({ fullPage: true }), contentType: 'image/png' });
    await page.unroute('**/livewire/update');
    await announcements.action('post', () => announcements.submit.click());
    await expect(announcements.form).not.toBeVisible();
    await expect(page.getByRole('table')).toContainText('Mobile draft');
    expect(db.snapshot().announcements.filter(row => row.title === 'Mobile draft')).toHaveLength(1);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
